"""`/etc/sudoers.d/df`: sudo rules of the stage-2 roles (spec 4.1, 4.4; Task 3).

`render` writes the exact text; `install` puts it in place atomically after
`visudo -c`. `policy_problems` and `io_log_problems` read the effective
policy back from `sudo -n -l -U <name>` (decision 13): the parser accepts only
the sections it knows. The listing is read from a pipe, which sudo never
wraps; joining wrapped lines (rules continue with deeper indentation, Defaults
bindings with a line that does not start a new `Defaults`) is a tolerance
only.
"""

from __future__ import annotations

import os
import re
import tempfile
import uuid
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from df import fsutil, platform, roles
from df.journal import StepFailed
from df.paths import Layout

SUDOERS_FILE = Path("/etc/sudoers.d/df")
VISUDO = "/usr/sbin/visudo"
_SUDO = "/usr/bin/sudo"
STEP = "sudoers"
#: Tags of every generated rule.
TAGS = frozenset({"NOPASSWD", "NOSETENV"})
#: Output streams of `df-publish` that sudo's I/O log must not record (4.4).
LOG_KEYS = ("log_output", "log_stdout", "log_stderr", "log_ttyout")
UNVERIFIABLE = "нарушено: конфигурация I/O-журнала не проверяема"
#: v1 supports classic sudo 1.9 only (owner, 27.10): sudo-rs (measured on the
#: Ubuntu 26.04 CI runner) rejects `log_output` and is refused with this
#: instruction.
SUDO_FIX = (
    "v1 требует классический sudo 1.9 (sudo.ws); переключите альтернативу sudo "
    "на sudo.ws (Ubuntu: `sudo update-alternatives --config sudo`)"
)
SudoFlavor = Literal["classic", "sudo-rs", "unknown"]
_CLASSIC = re.compile(r"Sudo version 1\.9\.\d+(?:p\d+)?")

_HEADER = "# generated by darkfactory roles setup; do not edit"
#: Roles allowed no sudo rule at all: `platform.sudo_rules(name) == "none"`.
_NO_RULES = frozenset({platform.BUILD_USER, "df-publisher"})
_RESERVED = frozenset({*roles.ROLE_USERS, "root", platform.BUILD_USER})
_USER_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_.-]*")
#: An upper-case word is a sudoers alias (`ALL` too), never a user.
_ALIAS = re.compile(r"[A-Z][A-Z0-9_]*")
_SAFE_PATH = re.compile(r"/[A-Za-z0-9/._-]*")
_PLAIN_USER = re.compile(r"[a-z_][a-z0-9_.-]*")
_TAG = re.compile(r"([A-Z_]+): |([A-Z_]+=\S+) ")
_BINDING = re.compile(r"Defaults([!>])(\S.*)")
#: One Defaults entry: `[!]name[{+,-}=value]`, a value quoted or one word.
_ENTRY = re.compile(r'!?[a-z_]+(?:[+-]?=(?:"[^"]*"|[^\s",]*))?')
_RULE_START = re.compile(r" {4}\(")
_CONTINUATION = ", \\\n    "

Lines = tuple[tuple[str, ...], ...]


@dataclass(frozen=True)
class Grant:
    """One command as `sudo -l` lists it: RunAs, tags and options, command."""

    runas: str
    tags: frozenset[str]
    command: str

    def __str__(self) -> str:
        tags = "".join(t + (" " if "=" in t else ": ") for t in sorted(self.tags))
        return f"({self.runas}) {tags}{self.command}"


@dataclass(frozen=True)
class Listing:
    """`sudo -l -U <name>` in parts; `bound` holds one binding per entry.

    sudo prints a RunAs change inside one privilege as a new line that shows
    only the tags that changed, so a line cannot tell a new privilege (no
    tag inherited) from the same one (tags inherited). `grants` reads every
    line as a new privilege, `carried` reads all lines as one; a tag that
    may apply is in either.
    """

    defaults: tuple[str, ...]
    bound: tuple[str, ...]
    grants: frozenset[Grant]
    carried: frozenset[Grant]


class ListingError(Exception):
    """The listing is not one this parser can read."""


# --- the text ------------------------------------------------------------------


def render(layout: Layout, operator: str) -> str:
    """The exact text of `/etc/sudoers.d/df`; paths come from `layout`."""
    publish = _command(layout, "df-publish")
    lines = [
        _HEADER,
        "Defaults:df-exec, df-review env_reset, !setenv",
        f"Defaults!{publish} !log_output",
    ]
    lines += [_rule_text(*rule) for rule in _rules(layout, operator)]
    return "\n".join(lines) + "\n"


def installed_operator(text: str, layout: Layout) -> str | None:
    """The operator a `render` text was made for: the caller of its
    `df-launch df-exec check` rule, only when exactly one line has that form
    (a second one, even planted, makes the name ambiguous: `None`)."""
    check = f"{_command(layout, 'df-launch')} df-exec check"
    callers = []
    for line in text.splitlines():
        caller, sep, rest = line.partition(" ALL=(df-exec) NOPASSWD: NOSETENV: ")
        if sep and rest.split(",")[0] == check:
            callers.append(caller)
    if len(callers) != 1 or not _USER_NAME.fullmatch(callers[0]):
        return None
    return callers[0]


def expected_grants(layout: Layout, operator: str) -> dict[str, frozenset[Grant]]:
    """What `render` grants, by invoking user."""
    found: dict[str, set[Grant]] = {}
    for caller, runas, lines in _rules(layout, operator):
        grants = {Grant(runas, TAGS, cmd) for line in lines for cmd in line}
        found.setdefault(caller, set()).update(grants)
    return {caller: frozenset(grants) for caller, grants in found.items()}


def _rules(layout: Layout, operator: str) -> tuple[tuple[str, str, Lines], ...]:
    """(caller, RunAs, commands by physical line) of every generated rule.

    A command with arguments allows exactly them; `df-review-run ""` allows
    none (a bare command would allow any).
    """
    op = _check_operator(operator)
    launch = _command(layout, "df-launch")
    review = _command(layout, "df-review-run")
    pub = _command(layout, "df-publish")
    violation, status = f"{pub} record-violation", f"{pub} perimeter-status"
    return (
        (
            op,
            "df-exec",
            ((f"{launch} df-exec check",), (f"{launch} df-exec check-github",)),
        ),
        (op, "df-review", ((f"{launch} df-review check",),)),
        ("df-exec", "df-review", ((f'{review} ""',),)),
        ("df-exec", "df-publisher", ((f"{pub} merge",), (violation,), (status,))),
        (
            "df-review",
            "df-publisher",
            (
                (),
                (f"{pub} publish-review", f"{pub} read-token"),
                (violation,),
                (status,),
            ),
        ),
    )


def _rule_text(caller: str, runas: str, lines: Lines) -> str:
    body = _CONTINUATION.join(", ".join(line) for line in lines if line)
    lead = " " if lines[0] else " \\\n    "
    return f"{caller} ALL=({runas}) NOPASSWD: NOSETENV:{lead}{body}"


def _check_operator(operator: str) -> str:
    if operator in _RESERVED:
        raise ValueError(f"operator cannot be a reserved account: {operator!r}")
    if not _USER_NAME.fullmatch(operator) or _ALIAS.fullmatch(operator):
        raise ValueError(f"invalid operator name for sudoers: {operator!r}")
    return operator


def _command(layout: Layout, name: str) -> str:
    path = str(layout.opt / "libexec" / name)
    if not _SAFE_PATH.fullmatch(path):
        raise ValueError(f"path not representable in sudoers: {path!r}")
    return path


# --- check and install ---------------------------------------------------------


def validate(text: str) -> list[str]:
    """`visudo -c -f <tmp>` of `text`; problems are its output lines."""
    fd, name = tempfile.mkstemp(prefix="df-sudoers.")
    try:
        with open(fd, "w", encoding="utf-8") as out:
            out.write(text)
        return _visudo_problems(Path(name))
    finally:
        os.unlink(name)


def sudo_flavor() -> SudoFlavor:
    """Which sudo `/usr/bin/sudo --version` names on its first line."""
    result = platform.run_command([_SUDO, "--version"])
    if not result.launched or result.returncode != 0:
        return "unknown"
    try:
        first = result.stdout.decode("utf-8").partition("\n")[0].strip()
    except UnicodeDecodeError:
        return "unknown"
    if _CLASSIC.fullmatch(first):
        return "classic"
    return "sudo-rs" if first.startswith("sudo-rs") else "unknown"


def flavor_problems() -> list[str]:
    """`[]` for classic sudo 1.9; otherwise a refusal naming `SUDO_FIX`."""
    flavor = sudo_flavor()
    return [] if flavor == "classic" else [f"sudo: найден {flavor}; {SUDO_FIX}"]


def install(text: str) -> None:
    """Write `SUDOERS_FILE` atomically: a `0440` root temp in the same
    directory, `visudo -c` of that temp, `rename`; otherwise `StepFailed`.

    Anything but classic sudo 1.9 is refused before any write."""
    problems = flavor_problems()
    if problems:
        raise StepFailed(STEP, "; ".join(problems))
    target = SUDOERS_FILE
    # sudo's `#includedir` skips names with a dot: the temp is never read.
    tmp = target.with_name(f".{target.name}.{uuid.uuid4().hex}.tmp")
    try:
        _place(tmp, target, text)
        fsutil.sync_dir(target.parent)
    except OSError as exc:
        raise StepFailed(STEP, f"{target}: {exc}") from exc


def _place(tmp: Path, target: Path, text: str) -> None:
    try:
        _write_root_file(tmp, text)
        problems = _visudo_problems(tmp)
        if problems:
            raise StepFailed(STEP, "; ".join(problems))
        os.rename(tmp, target)
    except BaseException:
        _discard(tmp)
        raise


def _write_root_file(path: Path, text: str) -> None:
    """Born `0440`, durable (`create_file`); owner and group are root's, the
    creator's (gid 0 on Linux, the directory's wheel on macOS)."""
    fd = fsutil.create_file(path, os.O_WRONLY | os.O_NOFOLLOW | os.O_CLOEXEC, 0o440)
    try:
        view = memoryview(text.encode("utf-8"))
        while view:
            view = view[os.write(fd, view) :]
        fsutil.sync_file(fd)
    finally:
        os.close(fd)


def _discard(path: Path) -> None:
    try:
        os.unlink(path)
    except FileNotFoundError:
        pass


def _visudo_problems(path: Path) -> list[str]:
    result = platform.run_command([VISUDO, "-c", "-f", str(path)])
    if not result.launched:
        return [f"{VISUDO}: не запустился"]
    if result.returncode == 0:
        return []
    output = (result.stdout + result.stderr).decode("utf-8", "replace")
    lines = [line.strip() for line in output.splitlines() if line.strip()]
    return lines or [f"{VISUDO}: код {result.returncode}"]


# --- the effective policy --------------------------------------------------------


def policy_problems(name: str, *, layout: Layout, operator: str) -> list[str]:
    """How the rules `sudo -n -l -U <name>` lists differ from `render`'s.

    `df-build`, `df-publisher`: no rule at all (`platform.sudo_rules`).
    `df-exec`, `df-review`: the set of (RunAs, tags, command) equals the
    generated one. The operator: the generated rules are in its set; the
    rest is not checked.
    """
    if name in _NO_RULES:
        rules = platform.sudo_rules(name)
        return [] if rules == "none" else [f"sudo -l -U {name}: {rules}"]
    expected = expected_grants(layout, operator)
    if name not in expected:
        raise ValueError(f"no sudo policy for {name!r}")
    try:
        have = read_listing(name).grants
    except ListingError as exc:
        return [f"sudo -l -U {name}: {exc}"]
    want = expected[name]
    extra = frozenset() if name == operator else have - want
    problems = [f"нет правила {g}" for g in sorted(want - have, key=str)]
    problems += [f"лишнее правило {g}" for g in sorted(extra, key=str)]
    return [f"sudo -l -U {name}: {p}" for p in problems]


def io_log_problems(layout: Layout) -> list[str]:
    """Whether sudo's I/O log can record the output of `df-publish` (4.4).

    Read from the effective Defaults `sudo -l -U` prints for `df-exec` and
    `df-review`: the last value of each of `LOG_KEYS` for the command must be
    off. Any `log_servers`, a log setting of undeterminable scope or an
    unrecognized line is `UNVERIFIABLE`, not success. Input logging is
    allowed (the publisher's stdin is the request, no secret).
    """
    publish = _command(layout, "df-publish")
    problems: list[str] = []
    for name in ("df-exec", "df-review"):
        try:
            found = _io_logged(read_listing(name), publish)
        except ListingError as exc:
            problems.append(f"sudo -l -U {name}: {UNVERIFIABLE}: {exc}")
            continue
        problems += [f"sudo -l -U {name}: {publish}: {item}" for item in found]
    return problems


def read_listing(name: str) -> Listing:
    """`LC_ALL=C sudo -n -l -U <name>`, parsed; `ListingError` otherwise."""
    result = platform.run_command([_SUDO, "-n", "-l", "-U", name])
    if not result.launched or result.returncode != 0:
        raise ListingError(f"sudo: код {result.returncode}")
    try:
        text = result.stdout.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ListingError(f"не UTF-8: {exc}") from exc
    return parse_listing(name, text)


def parse_listing(name: str, text: str) -> Listing:
    """The sections of a `sudo -l` text; anything unknown is `ListingError`."""
    sections = _sections(name, text)
    if ("rules" in sections) == ("none" in sections):
        raise ListingError("нет ровно одного из разделов правил")
    if sections.get("none"):
        raise ListingError(f"строка после отказа: {sections['none'][0]!r}")
    defaults = " ".join(line.strip() for line in sections.get("defaults", []))
    bound = _entries(sections.get("bound", []), _starts_binding)
    rules = _entries(sections.get("rules", []), _RULE_START.match)
    return Listing(
        defaults=tuple(_split_list(defaults)),
        bound=tuple(bound),
        grants=frozenset(_grants(rules, carry=False)),
        carried=frozenset(_grants(rules, carry=True)),
    )


def _sections(name: str, text: str) -> dict[str, list[str]]:
    user = re.escape(name)
    headers = {
        "defaults": re.compile(rf"Matching Defaults entries for {user} on \S+:"),
        "bound": re.compile(rf"Runas and Command-specific defaults for {user}:"),
        "rules": re.compile(rf"User {user} may run the following commands on \S+:"),
        "none": re.compile(rf"User {user} is not allowed to run sudo on \S+\."),
    }
    sections: dict[str, list[str]] = {}
    current: list[str] | None = None
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line:
            continue
        if line[0].isspace():
            if current is None:
                raise ListingError(f"строка вне раздела: {line!r}")
            current.append(line)
            continue
        kind = next((k for k, rx in headers.items() if rx.fullmatch(line)), None)
        if kind is None or kind in sections:
            raise ListingError(f"нераспознанная строка: {line!r}")
        current = sections[kind] = []
    return sections


def _starts_binding(line: str) -> bool:
    return line.lstrip().startswith("Defaults")


def _entries(lines: list[str], starts: Callable[[str], object]) -> list[str]:
    """Join wrapped lines: a line `starts` an entry, others continue it."""
    entries: list[str] = []
    for line in lines:
        if starts(line):
            entries.append(line.strip())
        elif entries:
            entries[-1] += " " + line.strip()
        else:
            raise ListingError(f"продолжение без начала: {line!r}")
    return entries


def _split_list(text: str) -> list[str]:
    """Split at `, ` outside quotes and parentheses; `\\` escapes a char."""
    items: list[str] = []
    start, depth, quoted, i = 0, 0, False, 0
    while i < len(text):
        ch = text[i]
        if ch == "\\":
            i += 2
            continue
        if ch == '"':
            quoted = not quoted
        elif not quoted and ch in "()":
            depth += 1 if ch == "(" else -1
        elif not quoted and depth == 0 and text.startswith(", ", i):
            items.append(text[start:i])
            start = i = i + 2
            continue
        i += 1
    items.append(text[start:])
    return [item.strip() for item in items if item.strip()]


def _grants(rules: list[str], *, carry: bool) -> Iterator[Grant]:
    """The listed commands; RunAs and tags carry along a line, and with
    `carry` from one line to the next too (see `Listing`)."""
    tags: dict[str, str] = {}
    for rule in rules:
        if not carry:
            tags = {}
        yield from _line_grants(rule, tags)


def _line_grants(rule: str, tags: dict[str, str]) -> Iterator[Grant]:
    """The commands of one listed line; updates `tags` as they change."""
    runas: str | None = None
    for listed in _split_list(rule):
        item = listed
        if item.startswith("("):
            close = item.find(")")
            if close < 0:
                raise ListingError(f"нераспознанное правило: {rule!r}")
            runas, item = item[1:close].strip(), item[close + 1 :].lstrip()
        if runas is None:
            raise ListingError(f"правило без RunAs: {rule!r}")
        while match := _TAG.match(item):
            tag = match.group(1) or match.group(2)
            key = tag.split("=")[0] if "=" in tag else tag.removeprefix("NO")
            tags[key] = tag
            item = item[match.end() :]
        if not item:
            raise ListingError(f"правило без команды: {rule!r}")
        yield Grant(runas, frozenset(tags.values()), item)


# --- I/O log -----------------------------------------------------------------------


def _io_logged(listing: Listing, publish: str) -> list[str]:
    """What logs the output of `publish`: keys on, a `LOG_OUTPUT` rule.

    sudo applies Defaults by class: generic, host and user (one section in
    `-l`, in file order, so mixed values there are undeterminable), then
    RunAs, then command bindings, each in file order.
    """
    values = _matching_values(listing.defaults)
    runas = [b for b in listing.bound if b.startswith("Defaults>")]
    cmnd = [b for b in listing.bound if b.startswith("Defaults!")]
    for binding in listing.bound:
        if binding not in runas + cmnd and _mentions(binding):
            raise ListingError(f"область не определима: {binding!r}")
    for binding in runas + cmnd:
        for entry in _bound_entries(binding, publish):
            setting = _log_setting(entry)
            if setting is not None:
                values[setting[0]] = setting[1]
    found = [f"{key} включён" for key in LOG_KEYS if values[key]]
    grants = listing.grants | listing.carried
    if any(_runs(g.command, publish) and "LOG_OUTPUT" in g.tags for g in grants):
        found.append("правило с тегом LOG_OUTPUT")
    return found


def _matching_values(entries: tuple[str, ...]) -> dict[str, bool]:
    seen: dict[str, set[bool]] = {}
    for entry in entries:
        setting = _log_setting(entry)
        if setting is not None:
            seen.setdefault(setting[0], set()).add(setting[1])
    mixed = [key for key, found in seen.items() if len(found) > 1]
    if mixed:
        raise ListingError(f"порядок уровней Defaults не определим: {mixed}")
    return {key: True in seen.get(key, set()) for key in LOG_KEYS}


def _bound_entries(binding: str, publish: str) -> list[str]:
    """The entries of a RunAs/command binding that applies to `publish`.

    A binding that mentions a log key must parse in full before its scope is
    judged: members without arguments, then entries of the Defaults grammar.
    sudo prints a `Cmnd_Alias` expanded, arguments included, so a member with
    arguments (`/x arg, /y log_output`) cannot be told from entries and is
    not verifiable.
    """
    if not _mentions(binding):
        return []
    if "log_servers" in binding:  # any mention, whatever the scope
        raise ListingError(f"log_servers: {binding!r}")
    match = _BINDING.fullmatch(binding)
    parts = _binding_parts(match.group(2)) if match else None
    if match is None or parts is None:
        raise ListingError(f"нераспознанная привязка: {binding!r}")
    members, entries = parts
    for entry in entries:
        _log_setting(entry)
    decide = _cmnd_member if match.group(1) == "!" else _runas_member
    verdicts = [decide(member, publish) for member in members]
    if None in verdicts:
        raise ListingError(f"область не определима: {binding!r}")
    return entries if any(verdicts) else []


def _binding_parts(rest: str) -> tuple[list[str], list[str]] | None:
    """(members, entries) of `M1, ..., Mk E1, ..., En`; `None` otherwise."""
    items = _split_list(rest)
    spaced = next((i for i, item in enumerate(items) if " " in item), None)
    if spaced is None:
        return None
    last, first = items[spaced].split(" ", 1)
    entries = [first, *items[spaced + 1 :]]
    if not all(_ENTRY.fullmatch(entry) for entry in entries):
        return None
    return [*items[:spaced], last], entries


def _cmnd_member(member: str, publish: str) -> bool | None:
    """Whether a command binding covers `publish`; `None`: cannot tell."""
    if member in ("ALL", publish):
        return True
    plain = _SAFE_PATH.fullmatch(member) and not member.endswith("/")
    # sudo matches a same-named command by inode too (a link to it).
    if not plain or Path(member).name == Path(publish).name:
        return None
    return False


def _runas_member(member: str, _publish: str) -> bool | None:
    """Whether a RunAs binding covers `df-publisher`; `None`: cannot tell."""
    if member in ("ALL", "df-publisher"):
        return True
    return False if _PLAIN_USER.fullmatch(member) else None


def _log_setting(entry: str) -> tuple[str, bool] | None:
    """(key, on) of a log-output entry; `ListingError` for any other mention."""
    if "log_servers" in entry:
        raise ListingError(f"log_servers: {entry!r}")
    for key in LOG_KEYS:
        if entry in (key, f"!{key}"):
            return key, entry == key
    if any(key in entry for key in LOG_KEYS):
        raise ListingError(f"нераспознанная запись: {entry!r}")
    return None


def _mentions(text: str) -> bool:
    return "log_servers" in text or any(key in text for key in LOG_KEYS)


def _runs(command: str, publish: str) -> bool:
    return command in ("ALL", publish) or command.startswith(f"{publish} ")
